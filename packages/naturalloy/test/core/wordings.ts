/**
 * Each pass, said in the canon under the spec it names: where it stands in the pipeline, how many formulas of the sweep
 * it changes, the shortest of them with the pass off and with every pass on, and what readers made of its words. The
 * regions are made from the passes and the sweep; run with `--write` to write them into CANON.md.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { say, sayDefinition } from '../../src/core/index.ts';
import type { Pass } from '../../src/core/pass.ts';
import { PASSES } from '../../src/core/passes/index.ts';
import { isDefinition, parseReadings, withDefinitions } from '../../src/index.ts';
import { READINGS, SWEEP, VOCABULARY } from '../canon/sweep.ts';

export const FILE = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'CANON.md');

const readings = withDefinitions(parseReadings(READINGS), VOCABULARY);

/** The words of a formula with every pass but those `off`, or undefined where it is refused. */
function words(formula: string, off: Set<string>): string | undefined {
  try {
    return isDefinition(formula) ? sayDefinition(formula, readings, { passes: PASSES, off }) : say(formula, readings, { passes: PASSES, off });
  } catch {
    return undefined;
  }
}

const begin = (pass: Pass): string => `<!-- pass-${pass.name}:begin — generated by \`node test/core/wordings.ts --write\`; edits are overwritten -->`;
const end = (pass: Pass): string => `<!-- pass-${pass.name}:end -->`;

/** What the region of a pass says. */
function region(pass: Pass, said: Map<string, string | undefined>): string {
  const off = new Set([pass.name]);
  const changed = SWEEP.map(({ formula }) => ({ formula, before: words(formula, off), after: said.get(formula) })).filter(c => c.after !== undefined && c.before !== c.after);
  const place = `${PASSES.indexOf(pass) + 1} of ${PASSES.length}`;
  const out = [`The pass \`${pass.name}\` is pass ${place} in the pipeline. It changes ${changed.length} of the ${SWEEP.length} formulas of the sweep.`];
  const shortest = changed.sort((a, b) => (a.after as string).length - (b.after as string).length || a.formula.localeCompare(b.formula))[0];
  if (shortest !== undefined) out.push('', 'The shortest of them, as written in Alloy:', '', '```text', shortest.formula, '```', '', 'Without the pass:', '', '```text', shortest.before ?? '(refused)', '```', '', 'With it:', '', '```text', shortest.after as string, '```');
  const notes = [...(pass.evidence?.readers ?? []).map(line => `- Readers: ${line}`), ...(pass.evidence?.rejected ?? []).map(line => `- Rejected: ${line}`)];
  if (notes.length > 0) out.push('', ...notes);
  return out.join('\n');
}

/** The canon with the region of each pass written under its spec: in place where it stands, and at the end of the spec where it does not. */
export function withRegions(canon: string): string {
  const said = new Map(SWEEP.map(({ formula }) => [formula, words(formula, new Set())]));
  let out = canon;
  for (const pass of PASSES) {
    const body = `${begin(pass)}\n${region(pass, said)}\n${end(pass)}`;
    const from = out.indexOf(`<!-- pass-${pass.name}:begin`);
    if (from !== -1) {
      const to = out.indexOf(end(pass), from) + end(pass).length;
      out = `${out.slice(0, from)}${body}${out.slice(to)}`;
      continue;
    }
    const heading = new RegExp(`^#+ @spec ${pass.spec.replace(/^spec-/, '')}\\n`, 'm').exec(out);
    if (heading === null) throw new Error(`the canon holds no spec "${pass.spec}" for the pass "${pass.name}"`);
    const next = /^#+ @/m.exec(out.slice(heading.index + heading[0].length));
    const at = next === null ? out.length : heading.index + heading[0].length + next.index;
    out = `${out.slice(0, at).trimEnd()}\n\n${body}\n\n${out.slice(at)}`;
  }
  return out;
}

if (process.argv.includes('--write')) writeFileSync(FILE, withRegions(readFileSync(FILE, 'utf8')));
