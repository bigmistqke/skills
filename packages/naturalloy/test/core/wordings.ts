/**
 * `WORDINGS.md`: what each pass does to the words, made from the passes and the sweep. For each pass, the spec that
 * states it, how many statements of the sweep it changes, the shortest of them with the pass off and on, and what
 * readers made of its words. Run with `--write` to write the file.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { say, sayDefinition } from '../../src/core/index.ts';
import { PASSES } from '../../src/core/passes/index.ts';
import { isDefinition, parseReadings, withDefinitions } from '../../src/index.ts';
import { READINGS, SWEEP, VOCABULARY } from '../canon/sweep.ts';

export const FILE = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'WORDINGS.md');

/** The words of a formula with every pass but those `off`, or undefined where it is refused. */
function words(formula: string, off: Set<string>): string | undefined {
  const readings = withDefinitions(parseReadings(READINGS), VOCABULARY);
  try {
    return isDefinition(formula) ? sayDefinition(formula, readings, { passes: PASSES, off }) : say(formula, readings, { passes: PASSES, off });
  } catch {
    return undefined;
  }
}

export function wordings(): string {
  const said = new Map(SWEEP.map(({ formula }) => [formula, words(formula, new Set())]));
  const out = [
    '# The wordings of naturalloy',
    '',
    '<!-- generated by `node test/core/wordings.ts --write`; edits are overwritten -->',
    '',
    'Each pass changes how a statement is said, and never what it means: the analyzer is asked of every change a pass makes to the IR of the sweep. With every pass off, the printer says the literal reading. A pass is shown here with the shortest statement of the sweep it changes, as it reads with that pass off and with every pass on.',
    ''
  ];
  for (const pass of PASSES) {
    const off = new Set([pass.name]);
    const changed = SWEEP.map(({ formula }) => ({ formula, before: words(formula, off), after: said.get(formula) })).filter(c => c.after !== undefined && c.before !== c.after);
    out.push(`## ${pass.name}`, '', `Spec: [\`${pass.spec}\`](CANON.md#${pass.spec}). It changes ${changed.length} of the ${SWEEP.length} formulas of the sweep.`, '');
    const shortest = changed.sort((a, b) => (a.after as string).length - (b.after as string).length || a.formula.localeCompare(b.formula))[0];
    if (shortest !== undefined) out.push('```alloy', shortest.formula, '```', '', 'Off:', '', '```text', shortest.before ?? '(refused)', '```', '', 'On:', '', '```text', shortest.after as string, '```', '');
    for (const line of pass.evidence?.readers ?? []) out.push(`- Readers: ${line}`);
    for (const line of pass.evidence?.rejected ?? []) out.push(`- Rejected: ${line}`);
    if (pass.evidence !== undefined) out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

if (process.argv.includes('--write')) writeFileSync(FILE, wordings());
else if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(readFileSync(FILE, 'utf8') === wordings() ? 'WORDINGS.md is current\n' : 'WORDINGS.md is stale: run node test/core/wordings.ts --write\n');
