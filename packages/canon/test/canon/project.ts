/**
 * A small project built in a temporary directory: one canon document under a
 * root axiom, and one test file. `check` runs over it, and each finding that
 * has entries comes back with its count. `checkTracked` runs it with a GitHub
 * tracker: a stub server on a local port that holds the issues it is given.
 */
import { spawn, spawnSync } from 'node:child_process';
import { createServer } from 'node:http';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach } from 'vitest';

const CLI = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'cli.ts');

const DIRS: string[] = [];
afterEach(() => {
  for (const dir of DIRS.splice(0)) rmSync(dir, { recursive: true, force: true });
});

/** A canon document whose root axiom is `axiom-a-program-means-one-thing`, with `units` after it. */
export const canon = (units: string): string => `# Canon

<!-- toc:begin — generated by \`canon generate\`; edits are overwritten -->
<!-- toc:end -->

## @axiom a-program-means-one-thing

> A program means one thing.
${units}`;

/** The tag a test cites a unit with, spelled apart so the checker does not read this file's template as a citation. */
const TAG = ['@', 'canon'].join('');

/** A test file's body: one test whose tag names `unit`, written with `call`, such as `it.fails`. */
export const tagged = (unit: string, call = 'it'): string => `/**\n * ${TAG} ${unit}\n */\n${call}('checks ${unit}', () => {});\n`;

/** What else a project holds: `files` by their path, the documents beside CANON.md, further settings of its canon field, and whether `generate` runs before the check. */
export interface Extra {
  files?: Record<string, string>;
  settings?: Record<string, unknown>;
  documents?: string[];
  generate?: boolean;
}

/** A project of the document and the test file, with a tracker if one is given. */
function project(document: string, tests: string, tracker?: Record<string, unknown>, extra: Extra = {}): string {
  const dir = mkdtempSync(join(tmpdir(), 'canon-of-canon-'));
  DIRS.push(dir);
  mkdirSync(join(dir, 'test', 'canon'), { recursive: true });
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ canon: { documents: ['CANON.md', ...(extra.documents ?? [])], suites: 'test/canon', sources: ['test'], command: 'canon', tracker, ...extra.settings } }));
  writeFileSync(join(dir, 'CANON.md'), document);
  if (tests) writeFileSync(join(dir, 'test', 'canon', 'a.test.ts'), tests);
  for (const [path, text] of Object.entries(extra.files ?? {})) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), text);
  }
  if (extra.generate !== false) spawnSync(process.execPath, [CLI, 'generate'], { cwd: dir });
  return dir;
}

/** A project of the document, the test file and what else it holds, left for a command to change; its directory. */
export function scratch(document: string, tests = '', extra: Extra = {}): string {
  return project(document, tests, undefined, extra);
}

/** Run the checker with `args` in the project at `dir`: its exit code, and what it printed. */
export function run(dir: string, ...args: string[]): { status: number | null; stdout: string; stderr: string } {
  const { status, stdout, stderr } = spawnSync(process.execPath, [CLI, ...args], { cwd: dir, encoding: 'utf8' });
  return { status, stdout, stderr };
}

/** The document as `generate` leaves it, in a project of it alone. */
export function generated(document: string): string {
  return readFileSync(join(project(document, ''), 'CANON.md'), 'utf8');
}

/** Each finding the output of `check` lists with any entries, and its count. */
function counts(out: string): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const line of out.split('\n')) {
    const found = /^(\S+) — .*: (\d+)$/.exec(line);
    if (found && Number(found[2]) > 0) counts[found[1] as string] = Number(found[2]);
  }
  return counts;
}

/** Run `check` over a project of the document, the test file and what else it holds, without a tracker. */
export function check(document: string, tests = '', extra: Extra = {}): Record<string, number> {
  const run = spawnSync(process.execPath, [CLI, 'check', '--offline'], { cwd: project(document, tests, undefined, extra), encoding: 'utf8' });
  return counts(run.stdout);
}

/** Run `check` over a project whose GitHub tracker holds `issues`, each number with its state. */
export async function checkTracked(document: string, tests: string, issues: Record<number, 'open' | 'closed'>): Promise<Record<string, number>> {
  const server = createServer((request, response) => {
    const number = /\/repos\/acme\/app\/issues\/(\d+)$/.exec(request.url ?? '')?.[1];
    const state = number === undefined ? undefined : issues[Number(number)];
    response.writeHead(state === undefined ? 404 : 200, { 'content-type': 'application/json' });
    response.end(JSON.stringify(state === undefined ? {} : { state }));
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  try {
    const host = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
    const dir = project(document, tests, { kind: 'github', repo: 'acme/app', host });
    const child = spawn(process.execPath, [CLI, 'check'], { cwd: dir, env: { ...process.env, GITHUB_TOKEN: 'token' } });
    let out = '';
    child.stdout.on('data', (chunk) => (out += chunk));
    await new Promise((resolve) => child.on('close', resolve));
    return counts(out);
  } finally {
    await new Promise<void>((resolve) => server.close(() => resolve()));
  }
}
