/**
 * What the logic layer does with the documents a document extends: the words
 * of the extended document say the statements of the document, its claims join
 * the model, and what belongs to it alone is left to it. Each case builds a
 * small project in a temporary directory and runs the command line over it.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { CLI, install } from './cli.ts';

/** The tags, spelled apart so the checker does not read this file's templates as citations. */
const AXIOM = ['@', 'axiom'].join('');
const TERM = ['@', 'term'].join('');
const TOC = '<!-- toc:begin — generated by `canon generate`; edits are overwritten -->\n<!-- toc:end -->';

const DIRS: string[] = [];
afterEach(() => {
  for (const dir of DIRS.splice(0)) rmSync(dir, { recursive: true, force: true });
});

/** The extended document: a word for nodes, and an axiom that says every node is done. */
const PARENT = `# Parent

${TOC}

## ${TERM} node

> A node is a thing that can be done.

\`\`\`alloy vocabulary
sig Node {}
sig Done in Node {}
\`\`\`

\`\`\`readings
noun Node: [node]
Done: {1} is [done] | {1} is not [done]
\`\`\`

## ${AXIOM} every-node-is-done

\`\`\`alloy
all n: Node | n in Done
\`\`\`
`;

/** The document that extends it, with `claim` as the formula of its own axiom and `own` added to the end. */
const child = (claim: string, own = ''): string => `---
plugins: ["@bigmistqke/canon-alloy"]
extends: ["../canon/CANON.md"]
---
# Child

${TOC}

## ${AXIOM} a-child-value

\`\`\`alloy bounds
for 3
\`\`\`

\`\`\`alloy
${claim}
\`\`\`
${own}`;

/** A project whose documents are the child only; `generate` has run over it, and then `command`. */
function project(files: Record<string, string>, command: string[]) {
  const dir = mkdtempSync(join(tmpdir(), 'canon-extends-logic-'));
  DIRS.push(dir);
  mkdirSync(join(dir, 'test', 'canon'), { recursive: true });
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ canon: { documents: ['alloy/CANON.md'], suites: 'test/canon', sources: ['test'], command: 'canon' } }));
  install(dir);
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), text);
  }
  const generated = spawnSync(process.execPath, [CLI, 'generate'], { cwd: dir, encoding: 'utf8' });
  const run = spawnSync(process.execPath, [CLI, ...command], { cwd: dir, encoding: 'utf8' });
  return { out: run.stdout, err: run.stderr, code: run.status, generated, read: (name: string) => readFileSync(join(dir, name), 'utf8') };
}

describe('the statements of a document that extends another', () => {
  /**
   * @canon spec-a-unit-is-said-with-the-readings-of-the-documents-its-document-extends
   * @canon spec-a-word-of-an-extended-document-links-to-that-document
   */
  it('say the words of the extended document, and link them to it', () => {
    const { read } = project({ 'alloy/CANON.md': child('all n: Node | n in Done'), 'canon/CANON.md': PARENT }, ['check']);
    const statement = read('alloy/CANON.md');
    expect(statement).toContain('For every [node_1](../canon/CANON.md#term-node):');
    expect(statement).toContain('node_1 is done');
  });

  /**
   * @canon spec-generate-writes-no-statement-for-a-unit-of-an-extended-document
   */
  it('leave the extended document as it is, with a unit that has no statement yet', () => {
    const { read } = project({ 'alloy/CANON.md': child('all n: Node | n in Done'), 'canon/CANON.md': PARENT }, ['check']);
    expect(read('canon/CANON.md')).toBe(PARENT);
  });

  /**
   * @canon spec-a-word-declared-in-an-extended-document-is-declared
   */
  it('count a word the extended document declares as declared, when the document gives its reading again', () => {
    const own = `\n## ${TERM} heavy\n\n> A node is heavy.\n\n\`\`\`alloy vocabulary\nsig Heavy in Node {}\n\`\`\`\n\n\`\`\`readings\nHeavy: {1} is heavy | {1} is not heavy\nDone: {1} is finished | {1} is not finished\n\`\`\`\n`;
    const { out } = project({ 'alloy/CANON.md': child('all n: Node | n in Heavy implies n in Done', own), 'canon/CANON.md': PARENT }, ['check']);
    expect(out).not.toContain('undeclared');
  });
});

describe.skipIf(!process.env.CANON_ALLOY_JAR)('the logic of a document that extends another', () => {
  afterEach(() => new Promise(resolve => setTimeout(resolve, 0)));

  /**
   * @canon spec-the-claims-of-an-extended-document-join-the-model
   * @canon spec-units-that-cannot-all-hold-are-named
   */
  it('finds a claim that contradicts a claim of the extended document, and names both', { timeout: 120_000 }, () => {
    const { out, code } = project({ 'alloy/CANON.md': child('some n: Node | n not in Done'), 'canon/CANON.md': PARENT }, ['logic']);
    expect(out).toContain('axiom-a-child-value');
    expect(out).toContain('axiom-every-node-is-done');
    expect(code).toBe(1);
  });

  /**
   * @canon spec-a-group-with-no-block-of-a-checked-document-is-not-asked-about
   */
  it('leaves a group of the extended document that the document has no block in to the extended document', { timeout: 120_000 }, () => {
    const alone = `\n## ${TERM} pear\n\n> A pear is sweet.\n\n\`\`\`alloy vocabulary\nsig Pear {}\nsig Sweet in Pear {}\n\`\`\`\n\n\`\`\`readings\nnoun Pear: [pear]\nSweet: {1} is [sweet] | {1} is not [sweet]\n\`\`\`\n\n## ${AXIOM} a-pear-is-sweet\n\n\`\`\`alloy\nall p: Pear | p in Sweet\n\`\`\`\n\n## ${AXIOM} a-pear-is-not-sweet\n\n\`\`\`alloy\nsome p: Pear | p not in Sweet\n\`\`\`\n`;
    const { out, code } = project({ 'alloy/CANON.md': child('all n: Node | n in Done'), 'canon/CANON.md': PARENT + alone }, ['logic']);
    expect(out).not.toContain('pear');
    expect(code).toBe(0);
  });
});
